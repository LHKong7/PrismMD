export function getThemeById(id: string): ThemeDefinition | undefined {
  return themes.find((t) => t.id === id)
}

export function applyTheme(theme: ThemeDefinition) {
  const root = document.documentElement

  // Apply CSS variables
  for (const [key, value] of Object.entries(theme.colors)) {
    root.style.setProperty(key, value)
  }

  // Toggle dark class
  if (theme.isDark) {
    root.classList.add('dark')
  } else {
    root.classList.remove('dark')
  }

  // Identity hooks for the Prism "reading instrument" design. `data-identity`
  // lets CSS scope per-theme signatures (e.g. Newsprint's drop cap + § heading
  // rules); `data-kind` exposes light/dark to selectors that don't want to rely
  // on the .dark class.
  root.setAttribute('data-identity', theme.id)
  root.setAttribute('data-kind', theme.isDark ? 'dark' : 'light')
}
